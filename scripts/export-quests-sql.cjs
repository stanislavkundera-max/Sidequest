/**
 * Emits SQL that upserts the catalogue into Supabase, generated from the
 * TypeScript source rather than typed by hand.
 *
 * There are two copies of the quest catalogue: `src/constants/quests.ts` (the
 * offline fallback, with journeys merged in from questJourneys.ts) and the
 * `quests` table Supabase actually serves. They had already drifted once —
 * every local quest was missing `suggestedGroup`, which silently cut the
 * Journey hub from nine suggestions to two. Generating one from the other is
 * how that stops happening.
 *
 * Usage:
 *   npx tsx scripts/export-quests-sql.cjs > supabase/quests_catalogue.sql
 *   (run through tsx because it imports the TypeScript catalogue)
 */
const { SEED_QUESTS } = require('../src/constants/quests');

/** Single-quote escaping for SQL string literals. */
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const jsonb = (v) => `${q(JSON.stringify(v))}::jsonb`;
const nullable = (s) => (s == null || s === '' ? 'null' : q(s));

const HEADER = `-- Side Quest Life quest catalogue.
--
-- GENERATED by scripts/export-quests-sql.cjs — do not edit by hand. Change the
-- quests in src/constants/quests.ts and questJourneys.ts, then re-run the
-- script, so the app's offline catalogue and the database cannot drift apart.
--
-- Safe to re-run: every row is an upsert. Existing rows keep their created_at
-- so the "newly added first" ordering is not reset by a refresh.
--
-- Requires supabase/quests_created_at.sql to have been run first.
`;

const rows = SEED_QUESTS.map((quest) => {
  const values = [
    q(quest.id),
    q(quest.title),
    q(quest.shortDescription),
    q(quest.fullDescription),
    q(quest.categoryId),
    q(quest.timeframe),
    q(quest.difficulty),
    String(quest.estimatedDurationMinutes),
    q(quest.promptForReflection),
    q(quest.suggestedProofType),
    nullable(quest.journeyIntro),
    jsonb(quest.actionSteps),
    nullable(quest.suggestedGroup),
  ].join(', ');
  return `  (${values})`;
});

console.log(HEADER);
console.log(`insert into public.quests (
  id, title, short_description, full_description, category_id, timeframe,
  difficulty, estimated_duration_minutes, prompt_for_reflection,
  suggested_proof_type, journey_intro, action_steps, suggested_group
) values`);
console.log(rows.join(',\n'));
console.log(`on conflict (id) do update set
  title = excluded.title,
  short_description = excluded.short_description,
  full_description = excluded.full_description,
  category_id = excluded.category_id,
  timeframe = excluded.timeframe,
  difficulty = excluded.difficulty,
  estimated_duration_minutes = excluded.estimated_duration_minutes,
  prompt_for_reflection = excluded.prompt_for_reflection,
  suggested_proof_type = excluded.suggested_proof_type,
  journey_intro = excluded.journey_intro,
  action_steps = excluded.action_steps,
  suggested_group = excluded.suggested_group;
  -- created_at is deliberately not updated: re-running this must not make the
  -- whole catalogue look newly added.
`);
console.log(`-- Verify.
select
  count(*) as total,
  count(*) filter (where suggested_group is null) as missing_group,
  count(*) filter (where jsonb_array_length(action_steps) = 0) as missing_steps
from public.quests;`);
